def _extract_routes(app_instance) -> set[tuple[str, tuple[str, ...]]]:
    routes = set()
    for ctx in routing.iter_route_contexts(app_instance.routes):
        route = getattr(ctx, "route", None)
        if route is not None and getattr(route, "methods", None):
            routes.add((route.path, tuple(sorted(route.methods))))
    return routes


def test_router_parity():
    current_routes = _extract_routes(app)

    missing_routes = GOLDEN_BASELINE - current_routes
    extra_routes = current_routes - GOLDEN_BASELINE

    assert not missing_routes, f"Missing routes from baseline: {sorted(missing_routes)}"
    assert not extra_routes, f"Unexpected extra routes: {sorted(extra_routes)}"
    assert current_routes == GOLDEN_BASELINE
